public class FloatProbe {
	public static void main(String[] args) {
		System.out.println(0.1f + 0.2f == 0.3f);
		System.out.println(0.1f + 0.6f == 0.7f);
		System.out.println(0.2f + 0.4f == 0.6f);
		System.out.println(0.3f + 0.6f == 0.9f);
		System.out.println(1f / 3f * 3f == 1f);
		System.out.println(0.7f - 0.1f == 0.6f);
	}
}
